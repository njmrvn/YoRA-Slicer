"""Write a toolpath as G-code (absolute E, no E resets) and read slicer G-code back into a toolpath.

Reading accepts output from PrusaSlicer, OrcaSlicer, Bambu Studio and Cura: G0/G1/G2/G3,
G90/G91, M82/M83, G92, G20/G21, and ;TYPE: / ;LAYER comments for feature types and layers.
E is rebuilt as one absolute, monotonic stream (relative E and G92 resets folded in), which is
what the Borunte_FGF post's absolute-E Extruder(E) calls expect.
"""
import json
import math
import re

import numpy as np

from .planner import toolpath_from_rows
from .slicer import (KIND_BRIM, KIND_INFILL, KIND_INNER, KIND_OUTER, KIND_RAFT, KIND_RETRACT, KIND_SOLID,
                     KIND_TRAVEL, KIND_NAMES)

WORD = re.compile(r'([A-Z])\s*([-+]?(?:\d+\.?\d*|\.\d+))')


def write_gcode(tp, s, name='print', hook=None):
    """G-code text. hook(event, layer=None) -> list of lines, called for post-processor events (program_start,
    layer_start / layer_end, travel_start / travel_end, extruder_on / extruder_off, program_end)."""
    ev = hook or (lambda event, layer=None: [])
    out = ['; Generated by YoRA Slicer for robot FGF printing',
           '; job: %s' % name,
           '; layers: %i  moves: %i' % (tp.stats.get('layers', 0), len(tp)),
           '; settings: ' + json.dumps(s, sort_keys=True),
           'G21 ; mm', 'G90 ; absolute XYZ', 'M82 ; absolute E', 'G92 E0']
    out += ev('program_start')
    px = py = pz = pe = pf = None
    cur_layer, cur_kind = -1, -1
    in_travel, extruding = False, False
    for i in range(len(tp)):
        x, y, z = (round(float(v), 3) for v in (tp.x[i], tp.y[i], tp.z[i]))
        e = round(float(tp.e[i]), 5)
        f = round(float(tp.f[i]) * 60.0, 1)
        kind, layer = int(tp.kind[i]), int(tp.layer[i])
        if hook is not None:
            if layer != cur_layer and cur_layer >= 0:
                out += ev('layer_end')
            if kind == KIND_TRAVEL and not in_travel:
                out += ev('travel_start')
                in_travel = True
            elif kind not in (KIND_TRAVEL, KIND_RETRACT) and in_travel:
                out += ev('travel_end')
                in_travel = False
            ext = pe is not None and e > pe + 1e-9 and kind != KIND_RETRACT
            if ext != extruding and (ext or kind == KIND_TRAVEL):
                out += ev('extruder_on' if ext else 'extruder_off')
                extruding = ext
        if layer != cur_layer:
            if hook is not None:
                out += ev('layer_start', layer)
            out.append(';LAYER_CHANGE')
            out.append(';Z:%.3f' % tp.layer_z[layer] if layer < len(tp.layer_z) else ';Z:%.3f' % z)
            out.append(';LAYER:%i' % layer)
            cur_layer = layer
        if kind != cur_kind and kind not in (KIND_TRAVEL, KIND_RETRACT):
            out.append(';TYPE:%s' % KIND_NAMES[kind])
            cur_kind = kind
        words = []
        if x != px:
            words.append('X%.3f' % x)
        if y != py:
            words.append('Y%.3f' % y)
        if z != pz:
            words.append('Z%.3f' % z)
        if e != pe:
            words.append('E%.5f' % e)
        if not words:
            continue
        if f != pf:
            words.append('F%.0f' % f)
        cmd = 'G0' if kind == KIND_TRAVEL and e == pe else 'G1'
        out.append(cmd + ' ' + ' '.join(words))
        px, py, pz, pe, pf = x, y, z, e, f
    if hook is not None:
        if cur_layer >= 0:
            out += ev('layer_end')
        if extruding:
            out += ev('extruder_off')
        out += ev('program_end')
    out.append('; end')
    return '\n'.join(out) + '\n'


TYPE_MAP = [  # (substring in ;TYPE: comment, kind) - first match wins
    ('outer', KIND_OUTER), ('external', KIND_OUTER), ('wall-outer', KIND_OUTER),
    ('overhang', KIND_OUTER),
    ('inner', KIND_INNER), ('perimeter', KIND_INNER), ('wall', KIND_INNER),
    ('solid', KIND_SOLID), ('top', KIND_SOLID), ('bottom', KIND_SOLID), ('skin', KIND_SOLID), ('ironing', KIND_SOLID),
    ('bridge', KIND_SOLID),
    ('skirt', KIND_BRIM), ('brim', KIND_BRIM), ('raft', KIND_RAFT), ('support interface', KIND_RAFT),
    ('infill', KIND_INFILL), ('fill', KIND_INFILL), ('support', KIND_INFILL),
]


def _kind_from_type(text):
    t = text.lower()
    for key, kind in TYPE_MAP:
        if key in t:
            return kind
    return KIND_INFILL


def read_gcode(text, s):
    """Parse slicer G-code into a Toolpath. Returns (toolpath, info)."""
    rows = []
    pos = [0.0, 0.0, 0.0]
    have_pos = False
    abs_xyz, abs_e, unit = True, True, 1.0
    e_offset = e_raw = e_abs = 0.0
    feed = s['travel_speed']
    kind_hint = KIND_INFILL
    layer, layer_z = -1, []
    pending_layer = False
    used_comments = False
    ignored, arcs_r = {}, 0

    def start_layer(z):
        nonlocal layer
        layer += 1
        layer_z.append(z)

    for raw in text.splitlines():
        line = raw.strip()
        if line.startswith(';'):
            c = line[1:].strip()
            cu = c.upper()
            if cu.startswith('TYPE:'):
                kind_hint = _kind_from_type(c[5:])
            elif cu.startswith('LAYER_CHANGE') or re.match(r'LAYER:\s*-?\d+', cu):
                pending_layer = True
                used_comments = True
            continue
        code = re.sub(r'\(.*?\)', '', line.split(';', 1)[0]).upper()
        words = WORD.findall(code)
        if not words:
            continue
        cmd, p = None, {}
        for letter, value in words:
            if letter in 'GM' and cmd is None:
                cmd = '%s%i' % (letter, int(float(value)))
            else:
                p[letter] = float(value)
        if cmd is None and any(a in p for a in 'XYZE'):
            cmd = 'G1'
        if cmd in ('G0', 'G1', 'G2', 'G3'):
            if 'F' in p:
                feed = p['F'] * unit / 60.0
            target = list(pos)
            for i, a in enumerate('XYZ'):
                if a in p:
                    target[i] = p[a] * unit if abs_xyz else pos[i] + p[a] * unit
            e_before = e_abs
            if 'E' in p:
                if abs_e:
                    e_raw = p['E'] * unit
                    e_abs = e_offset + e_raw
                else:
                    e_abs += p['E'] * unit
            moved = any(abs(target[i] - pos[i]) > 1e-9 for i in range(3))
            extruding = e_abs > e_before + 1e-9 and moved and cmd != 'G0'
            if extruding and (layer < 0 or (pending_layer if used_comments else target[2] > layer_z[-1] + 0.05)):
                start_layer(target[2])
                pending_layer = False
            lay = max(layer, 0)
            if cmd in ('G2', 'G3') and ('I' in p or 'J' in p):
                pts = _arc(pos, target, p.get('I', 0.0) * unit, p.get('J', 0.0) * unit, cmd == 'G2')
            else:
                if cmd in ('G2', 'G3'):
                    arcs_r += 1
                pts = [target]
            if not have_pos:
                have_pos = True
                pos = target
                rows.append((pos[0], pos[1], pos[2], e_abs, feed, KIND_TRAVEL, lay))
                continue
            if not moved:
                if abs(e_abs - e_before) > 1e-9:
                    rows.append((pos[0], pos[1], pos[2], e_abs, feed, KIND_RETRACT, lay))
                continue
            kind = kind_hint if extruding else KIND_TRAVEL
            # spread E over arc pieces in proportion to length
            seglens = [math.dist(a, b) for a, b in zip([pos] + pts[:-1], pts)]
            total = sum(seglens) or 1.0
            acc = 0.0
            for q, L in zip(pts, seglens):
                acc += L
                rows.append((q[0], q[1], q[2], e_before + (e_abs - e_before) * acc / total, feed, kind, lay))
            pos = target
        elif cmd == 'G90':
            abs_xyz = True
        elif cmd == 'G91':
            abs_xyz = False
        elif cmd == 'M82':
            abs_e = True
        elif cmd == 'M83':
            abs_e = False
        elif cmd == 'G20':
            unit = 25.4
        elif cmd == 'G21':
            unit = 1.0
        elif cmd == 'G92':
            if 'E' in p:
                e_raw = p['E'] * unit
                e_offset = e_abs - e_raw
            for i, a in enumerate('XYZ'):
                if a in p:
                    pos[i] = p[a] * unit
        elif cmd is not None:
            ignored[cmd] = ignored.get(cmd, 0) + 1
    if not rows:
        raise ValueError('No moves found in the G-code')
    warnings = []
    if arcs_r:
        warnings.append('%i arc moves with R were treated as straight lines.' % arcs_r)
    if not layer_z:
        layer_z = [0.0]
    tp = toolpath_from_rows(rows, layer_z, s, warnings)
    return tp, {'ignored': ignored, 'layers_from': 'comments' if used_comments else 'Z changes'}


def _arc(p0, p1, i, j, clockwise, max_seg=1.0):
    cx, cy = p0[0] + i, p0[1] + j
    r = math.hypot(p0[0] - cx, p0[1] - cy)
    a0 = math.atan2(p0[1] - cy, p0[0] - cx)
    a1 = math.atan2(p1[1] - cy, p1[0] - cx)
    sweep = a1 - a0
    if clockwise and sweep >= 0:
        sweep -= 2 * math.pi
    elif not clockwise and sweep <= 0:
        sweep += 2 * math.pi
    n = max(2, int(math.ceil(abs(sweep) * r / max_seg)))
    pts = []
    for k in range(1, n + 1):
        a = a0 + sweep * k / n
        pts.append([cx + r * math.cos(a), cy + r * math.sin(a), p0[2] + (p1[2] - p0[2]) * k / n])
    pts[-1] = list(p1)
    return pts
